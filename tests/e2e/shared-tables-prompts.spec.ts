import { readFile } from 'node:fs/promises'
import { test, expect } from '../../frontend/playwright-fixtures'

test.use({ mockProviders: true })

test('edits shared tables, previews an import and downloads a compatible bundle', async ({ page, backend }, testInfo) => {
  await page.goto(backend.handoff('/tables/glossary'))
  await expect(page.getByRole('heading', { name: '术语表', exact: true })).toBeVisible()
  await page.getByRole('textbox', { name: '子表名称', exact: true }).fill('M4 manual terms')
  await page.getByRole('button', { name: '添加条目', exact: true }).click()
  await page.getByRole('textbox', { name: '原文 1', exact: true }).fill('Alice')
  await page.getByRole('textbox', { name: '译文 1', exact: true }).fill('爱丽丝')
  await page.getByRole('checkbox', { name: '区分大小写', exact: true }).check()
  await page.getByRole('button', { name: '保存更改', exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: '已保存' })).toBeVisible()
  await expect.poll(async () => (await backend.readConfig()).prompt_dictionary_tables).toEqual(expect.arrayContaining([expect.objectContaining({ name: 'M4 manual terms', match_options: expect.objectContaining({ case_sensitive: true }), rows: expect.arrayContaining([expect.objectContaining({ src: 'Alice', dst: '爱丽丝' })]) })]))

  await page.getByRole('button', { name: '导入', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.locator('input[type=file]').setInputFiles({ name: 'imported-terms.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify([{ src: 'Bob', dst: '鲍勃', future: { origin: 'fixed e2e fixture' } }])) })
  await expect(dialog.getByText('imported-terms', { exact: true })).toBeVisible()
  expect((await backend.readConfig()).prompt_dictionary_tables).toHaveLength(1)
  await dialog.getByRole('button', { name: '导入选中子表', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  await expect(page.getByRole('textbox', { name: '原文 1', exact: true })).toHaveValue('Bob')
  await page.getByRole('textbox', { name: '译文 1', exact: true }).fill('鲍勃先生')
  await page.getByRole('button', { name: '保存更改', exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: '已保存' })).toBeVisible()

  const downloading = page.waitForEvent('download')
  await page.getByRole('button', { name: '导出所有子表', exact: true }).click()
  const download = await downloading
  const filename = testInfo.outputPath('shared-tables.json')
  await download.saveAs(filename)
  const bundle = JSON.parse(await readFile(filename, 'utf8'))
  expect(bundle).toMatchObject({ format: 'ainiee.public_tables', version: 1, kind: 'prompt_dictionary' })
  expect(bundle.tables).toHaveLength(2)
  expect(bundle.tables[1].rows[0]).toMatchObject({ src: 'Bob', dst: '鲍勃先生', future: { origin: 'fixed e2e fixture' } })
  await page.reload()
  await expect(page.getByRole('textbox', { name: '译文 1', exact: true })).toHaveValue('鲍勃先生')
  await page.screenshot({ path: testInfo.outputPath('m4-shared-tables.png'), fullPage: true })
})

test('creates, edits, selects and removes custom prompts and saves world context', async ({ page, backend }, testInfo) => {
  await page.goto(backend.handoff('/prompts/library'))
  await page.getByRole('button', { name: '新建提示词', exact: true }).click()
  let dialog = page.getByRole('dialog')
  await dialog.getByRole('textbox', { name: '名称', exact: true }).fill('M4 custom prompt')
  await dialog.getByRole('textbox', { name: '提示内容', exact: true }).fill('Fixed manual translation guidance.')
  await dialog.getByRole('button', { name: '保存', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  await expect(page.getByText('Fixed manual translation guidance.', { exact: true })).toBeVisible()
  const selected = (await backend.readConfig()).translation_prompt_selection
  expect(selected).toMatchObject({ prompt_content: 'Fixed manual translation guidance.' })
  await page.getByRole('button', { name: '编辑提示词', exact: true }).click()
  dialog = page.getByRole('dialog')
  await dialog.getByRole('textbox', { name: '提示内容', exact: true }).fill('Edited fixed guidance.')
  await dialog.getByRole('button', { name: '保存', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  await expect(page.getByText('Edited fixed guidance.', { exact: true })).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('m4-prompt-library.png'), fullPage: true })
  await page.getByRole('button', { name: '删除提示词', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: '删除提示词', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect.poll(async () => (await backend.readConfig()).translation_prompt_selection).toMatchObject({ last_selected_id: 100 })
  await page.getByRole('link', { name: '背景设定', exact: true }).click()
  await page.getByRole('textbox', { name: '提示内容', exact: true }).fill('A fixed fantasy world.')
  await page.getByRole('checkbox', { name: /启用此提示/ }).check()
  await page.getByRole('button', { name: '保存', exact: true }).click()
  await expect.poll(async () => (await backend.readConfig()).world_building_content).toBe('A fixed fantasy world.')
  await page.reload()
  await expect(page.getByRole('textbox', { name: '提示内容', exact: true })).toHaveValue('A fixed fantasy world.')
})
