import { mkdir, writeFile } from 'node:fs/promises'
import { join } from 'node:path'
import { test, expect } from '../../frontend/playwright-fixtures'
import type { components } from '../../frontend/src/api/generated/schema'

test.use({ mockProviders: true })

test('configure an interface and open a real local project with statistics and a file tree', async ({ page, backend }, testInfo) => {
  const source = join(backend.directory, 'source')
  await mkdir(join(source, 'sub'), { recursive: true })
  await writeFile(join(source, 'intro.txt'), 'Hello from the introduction.\nA second source line.\n', 'utf8')
  await writeFile(join(source, 'sub', 'chapter.txt'), 'Welcome to the chapter.\nThe story continues here.\n', 'utf8')
  const externalRequests: string[] = []
  page.on('request', request => {
    const url = new URL(request.url())
    if (url.protocol.startsWith('http') && url.hostname !== '127.0.0.1') externalRequests.push(url.origin)
  })

  await page.goto(backend.handoff('/platforms'))
  await expect(page.getByRole('heading', { name: '接口管理', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '添加接口', exact: true }).first().click()
  const create = page.getByRole('dialog', { name: '添加接口', exact: true })
  await create.getByLabel('平台预设', { exact: true }).selectOption('custom')
  await create.getByLabel('接口名称', { exact: true }).fill('M3 固定接口')
  await create.getByLabel('模型名称', { exact: true }).fill('fixed-mock-model')
  await create.getByLabel('接口地址', { exact: true }).fill('https://llm.invalid')
  await create.getByLabel('API Key', { exact: true }).fill('fixed-test-key')
  await create.getByRole('button', { name: '保存', exact: true }).click()
  const created = page.getByRole('article', { name: 'M3 固定接口', exact: true })
  await expect(created).toBeVisible()
  await expect(created).not.toContainText('fixed-test-key')

  await created.getByRole('button', { name: '编辑接口', exact: true }).click()
  const edit = page.getByRole('dialog', { name: '编辑接口', exact: true })
  await edit.getByLabel('接口名称', { exact: true }).fill('M3 校验接口')
  await edit.getByRole('tab', { name: '请求参数', exact: true }).click()
  await edit.getByLabel('温度', { exact: true }).fill('0.7')
  await edit.getByRole('button', { name: '保存', exact: true }).click()
  const card = page.getByRole('article', { name: 'M3 校验接口', exact: true })
  await expect(card).toBeVisible()
  const bindings = page.getByRole('region', { name: '功能接口绑定', exact: true })
  await bindings.getByLabel('激活接口', { exact: true }).selectOption({ label: 'M3 校验接口' })
  await bindings.getByLabel('翻译接口', { exact: true }).selectOption({ label: 'M3 校验接口' })
  await bindings.getByRole('button', { name: '保存', exact: true }).click()
  await expect(card.getByText('已激活', { exact: true })).toBeVisible()

  await card.getByRole('button', { name: '测试连接', exact: true }).click()
  const testResult = page.getByRole('dialog', { name: '接口测试结果 · M3 校验接口', exact: true })
  await expect(testResult.getByRole('status')).toHaveText('成功 1，失败 0')
  await expect(testResult.getByText('连接成功', { exact: true })).toBeVisible()
  await expect(testResult).not.toContainText('fixed-test-key')
  await testResult.getByRole('button', { name: '关闭', exact: true }).last().click()

  await card.getByRole('button', { name: '浏览模型', exact: true }).click()
  const browser = page.getByRole('dialog', { name: '可用模型 · M3 校验接口', exact: true })
  await expect(browser.getByLabel('fixed-second-model', { exact: true })).toBeVisible()
  await browser.getByRole('textbox', { name: '搜索模型', exact: true }).fill('second')
  await browser.getByLabel('fixed-second-model', { exact: true }).check()
  await browser.getByRole('button', { name: '添加所选模型', exact: true }).click()
  await expect(card.getByText('fixed-second-model', { exact: true })).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('m3-platforms.png'), fullPage: true })

  await page.getByRole('link', { name: '首页', exact: true }).click()
  await page.getByRole('textbox', { name: '项目路径', exact: true }).fill(backend.directory)
  await page.getByRole('button', { name: '浏览文件夹', exact: true }).click()
  const directory = page.getByRole('dialog', { name: '选择项目文件夹', exact: true })
  await directory.getByRole('button', { name: 'source', exact: true }).click()
  await expect(directory.getByRole('button', { name: 'sub', exact: true })).toBeVisible()
  await directory.getByRole('button', { name: '选择此文件夹', exact: true }).click()
  await expect(page.getByRole('textbox', { name: '项目路径', exact: true })).toHaveValue(source)
  await page.getByRole('combobox', { name: '项目类型', exact: true }).selectOption('Txt')
  await expect(page.getByRole('combobox', { name: '项目类型', exact: true })).toBeEnabled()
  const openedResponse = page.waitForResponse(response => response.url() === `${backend.origin}/api/v1/projects/open` && response.ok())
  await page.getByRole('button', { name: '打开项目', exact: true }).click()
  const opened: components['schemas']['ProjectSummary'] = await (await openedResponse).json()
  await expect(page.getByRole('heading', { name: '项目概览', exact: true })).toBeVisible()
  await expect(page.locator('.project-summary').getByRole('heading', { name: opened.project_name, exact: true })).toBeVisible()
  await expect(page.locator('.project-stat').filter({ hasText: /^文件2$/ }).locator('strong')).toHaveText('2')
  await expect(page.locator('.project-stat').filter({ hasText: /^条目4$/ }).locator('strong')).toHaveText('4')
  await expect(page.getByRole('button', { name: 'intro.txt 2', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'chapter.txt 2', exact: true }).click()
  await expect(page.locator('.project-file-details').getByRole('heading', { name: /sub[/\\]chapter\.txt/ })).toBeVisible()
  await expect(page.locator('.project-file-details')).toContainText('Txt')
  await page.getByRole('textbox', { name: '筛选文件', exact: true }).fill('chapter')
  await expect(page.getByRole('button', { name: 'intro.txt 2', exact: true })).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'chapter.txt 2', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await page.screenshot({ path: testInfo.outputPath('m3-project-overview.png'), fullPage: true })

  await page.getByRole('link', { name: '首页', exact: true }).click()
  const history = page.getByRole('region', { name: '最近的项目', exact: true })
  await expect(page.getByRole('button', { name: '打开项目', exact: true })).toBeEnabled()
  await expect(history.getByRole('article', { name: opened.project_name, exact: true })).toBeVisible()
  await expect(history.getByRole('link', { name: '查看项目', exact: true })).toBeVisible()
  await expect(history.getByRole('button', { name: `删除缓存 ${opened.project_name}`, exact: true })).toBeDisabled()
  await page.screenshot({ path: testInfo.outputPath('m3-home.png'), fullPage: true })
  await backend.restart()
  await expect(history.getByRole('button', { name: '继续项目', exact: true })).toBeVisible()
  const resumedResponse = page.waitForResponse(response => response.url() === `${backend.origin}/api/v1/projects/open` && response.ok())
  await history.getByRole('button', { name: '继续项目', exact: true }).click()
  const resumed: components['schemas']['ProjectSummary'] = await (await resumedResponse).json()
  expect(resumed.project_id).toBe(opened.project_id)
  await expect(page.getByRole('heading', { name: '项目概览', exact: true })).toBeVisible()
  await expect(page.locator('.project-stat').filter({ hasText: /^条目4$/ }).locator('strong')).toHaveText('4')
  await expect(page.getByRole('button', { name: 'intro.txt 2', exact: true })).toBeVisible()
  expect(externalRequests).toEqual([])
})
