import { test, expect } from '../../frontend/playwright-fixtures'

test('three settings pages persist through a real backend restart and WebSocket reconnect', async ({ page, backend }, testInfo) => {
  const unexpectedRequests: string[] = []
  page.on('request', request => {
    const url = new URL(request.url())
    if (url.protocol.startsWith('http') && url.hostname !== '127.0.0.1') unexpectedRequests.push(url.origin)
    if (url.pathname.startsWith('/api/v1/tasks/') && url.pathname !== '/api/v1/tasks/current') unexpectedRequests.push(url.pathname)
    if (url.pathname.includes('/update/check')) unexpectedRequests.push(url.pathname)
  })
  await page.goto(backend.handoff('/settings/task'))
  await expect(page.getByRole('heading', { name: '任务设置', exact: true })).toBeVisible()
  await page.getByRole('combobox', { name: '任务切分模式' }).selectOption('lines')
  const lines = page.getByRole('spinbutton', { name: '任务的文本行数', exact: true })
  await lines.fill('37')
  await lines.press('Tab')
  await expect.poll(async () => (await backend.readConfig()).lines_limit).toBe(37)

  await page.getByRole('link', { name: '输出设置', exact: true }).click()
  const suffix = page.getByRole('textbox', { name: '输出文件名后缀' })
  await suffix.fill('_m2_checked')
  await suffix.press('Tab')
  await expect.poll(async () => (await backend.readConfig()).output_filename_suffix).toBe('_m2_checked')
  await expect(page.getByRole('textbox', { name: '翻译输出文件夹', exact: true })).toBeDisabled()

  await page.getByRole('link', { name: '高级设置', exact: true }).click()
  const contextLines = page.getByRole('spinbutton', { name: '参考上文行数', exact: true })
  await contextLines.fill('6')
  await contextLines.press('Tab')
  await expect.poll(async () => (await backend.readConfig()).pre_line_counts).toBe(6)
  expect(await backend.readPersistedConfig()).toMatchObject({
    lines_limit: 37, lines_limit_switch: true, tokens_limit_switch: false,
    output_filename_suffix: '_m2_checked', pre_line_counts: 6,
  })

  await backend.stop()
  await expect(page.getByRole('button', { name: '连接设置', exact: true }).filter({ hasText: '正在重新连接' })).toBeVisible()
  const taskRefresh = page.waitForResponse(response => response.url() === `${backend.origin}/api/v1/tasks/current` && response.ok())
  const configRefresh = page.waitForResponse(response => response.url() === `${backend.origin}/api/v1/config` && response.ok())
  await backend.start(backend.port)
  await Promise.all([taskRefresh, configRefresh])
  await expect(page.getByRole('button', { name: '连接设置', exact: true }).filter({ hasText: '服务已连接' })).toBeVisible()
  await expect(contextLines).toHaveValue('6')
  await page.reload()
  await expect(page.getByRole('spinbutton', { name: '参考上文行数', exact: true })).toHaveValue('6')
  await page.getByRole('link', { name: '输出设置', exact: true }).click()
  await expect(page.getByRole('textbox', { name: '输出文件名后缀' })).toHaveValue('_m2_checked')
  await page.getByRole('link', { name: '任务设置', exact: true }).click()
  await expect(page.getByRole('spinbutton', { name: '任务的文本行数', exact: true })).toHaveValue('37')
  expect(new URL(page.url()).hash).toBe('')
  expect(unexpectedRequests).toEqual([])
  await page.screenshot({ path: testInfo.outputPath('m2-light.png'), fullPage: true })
})

test('language, theme, and assistant panel work with persisted preferences', async ({ page, backend }, testInfo) => {
  await page.goto(backend.handoff('/settings/app'))
  await expect(page.getByRole('heading', { name: '应用设置', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '浅色', exact: true }).click()
  await expect.poll(async () => (await backend.readConfig()).theme).toBe('light')
  await page.keyboard.press('Control+l')
  const panel = page.getByRole('complementary', { name: '智能体助手' })
  await expect(panel).toBeVisible()
  await expect(panel.getByRole('textbox')).toBeDisabled()
  await page.reload()
  await expect(panel).toBeVisible()
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem('ainiee.layout') ?? '{}').agentPanelOpen)).toBe(true)
  await page.screenshot({ path: testInfo.outputPath('m2-assistant-light.png'), fullPage: true })

  await page.getByRole('button', { name: '深色', exact: true }).click()
  await expect(page.locator('html')).toHaveClass(/dark/)
  await page.getByRole('combobox', { name: '界面语言', exact: true }).selectOption('English')
  await expect(page.getByRole('heading', { name: 'App settings', exact: true })).toBeVisible()
  await expect(page.locator('html')).toHaveAttribute('lang', 'en')
  await expect(page.getByRole('heading', { name: 'Your assistant is coming soon' })).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('m2-dark-english.png'), fullPage: true })
  await page.reload()
  await expect(page.getByRole('heading', { name: 'App settings', exact: true })).toBeVisible()
  await expect(page.locator('html')).toHaveClass(/dark/)
  await page.keyboard.press('Control+l')
  await expect(page.getByRole('complementary', { name: 'AI assistant' })).toHaveCount(0)
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem('ainiee.layout') ?? '{}').agentPanelOpen)).toBe(false)
  expect(await backend.readPersistedConfig()).toMatchObject({ theme: 'dark', interface_language_setting: 'English' })
})
